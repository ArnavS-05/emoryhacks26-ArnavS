import type { ButtonHTMLAttributes, ReactNode } from 'react'
import { useEffect, useState } from 'react'
import { Loader2 } from 'lucide-react'
import { api } from '../lib/api'

export function Card({ title, actions, children, className = '', id }: { title?: ReactNode; actions?: ReactNode; children: ReactNode; className?: string; id?: string }) {
  return (
    <section id={id} className={`rounded-2xl border border-line bg-white shadow-[0_1px_2px_rgb(16_42_67/0.06)] ${className}`}>
      {(title || actions) && (
        <header className="flex items-center justify-between gap-3 border-b border-line px-5 py-3">
          {title && <h2 className="text-[15px] font-semibold text-navy">{title}</h2>}
          {actions}
        </header>
      )}
      <div className="p-5">{children}</div>
    </section>
  )
}

type BtnProps = ButtonHTMLAttributes<HTMLButtonElement> & { variant?: 'primary' | 'secondary' | 'ghost' | 'danger'; loading?: boolean; size?: 'sm' | 'md' }
export function Button({ variant = 'primary', loading, size = 'md', className = '', children, disabled, ...rest }: BtnProps) {
  const v = {
    primary: 'bg-teal text-white hover:bg-teal-700',
    secondary: 'border border-line bg-white text-navy hover:border-teal',
    ghost: 'text-navy hover:bg-soft',
    danger: 'bg-urgent text-white hover:opacity-90',
  }[variant]
  const s = size === 'sm' ? 'px-3 py-1.5 text-sm' : 'px-4 py-2 text-sm'
  return (
    <button {...rest} disabled={disabled || loading} className={`inline-flex items-center justify-center gap-2 rounded-xl font-semibold transition-colors disabled:cursor-not-allowed disabled:opacity-50 ${v} ${s} ${className}`}>
      {loading && <Loader2 className="size-4 animate-spin" aria-hidden />}
      {children}
    </button>
  )
}

export function Badge({ tone = 'neutral', children, title }: { tone?: 'neutral' | 'teal' | 'amber' | 'urgent' | 'navy'; children: ReactNode; title?: string }) {
  const t = {
    neutral: 'bg-soft text-navy-500 border-line',
    teal: 'bg-ice text-teal-700 border-teal-100',
    amber: 'bg-amber-100 text-[#7a4b00] border-amber',
    urgent: 'bg-urgent-100 text-urgent border-urgent/30',
    navy: 'bg-navy text-white border-navy',
  }[tone]
  return <span title={title} className={`inline-flex items-center gap-1 rounded-full border px-2 py-0.5 text-xs font-semibold ${t}`}>{children}</span>
}

/** Label for any AI-produced content: shows the model or flags fallback. */
export function EngineBadge({ engine }: { engine?: string | null }) {
  if (!engine) return null
  if (engine.startsWith('fallback') || engine === 'unavailable') return <Badge tone="amber" title="AI unavailable — deterministic fallback used">Fallback · {engine.replace('fallback:', '')}</Badge>
  if (engine === 'patient-confirmed') return <Badge tone="teal">Patient-confirmed</Badge>
  return <Badge tone="navy" title="Generated by Gemini">Gemini · {engine}</Badge>
}

