export function ErrorNote({ error }: { error?: string | null }) {
  if (!error) return null
  return <p role="alert" className="rounded-xl border border-urgent/30 bg-urgent-100 px-3 py-2 text-sm text-urgent">{error}</p>
}

/** Real connection indicators from /api/status (no secrets). */
export function ConnectionIndicators() {
  const [s, setS] = useState<any>(null)
  useEffect(() => {
    const load = () => api('/api/status').then(setS).catch(() => setS({ error: true }))
    void load()
    const t = setInterval(load, 30000)
    return () => clearInterval(t)
  }, [])
  if (!s) return null
  if (s.error) return <Badge tone="urgent">API offline</Badge>
  const dot = (ok: boolean, warn = false) => <span className={`inline-block size-2 rounded-full ${ok ? 'bg-teal' : warn ? 'bg-amber' : 'bg-navy-300'}`} />
  return (
    <div className="flex items-center gap-3 text-xs text-navy-500" aria-label="Service connections">
      <span className="flex items-center gap-1">{dot(s.gemini === 'configured', true)}Gemini</span>
      <span className="flex items-center gap-1">{dot(s.typesense === 'connected', s.typesense === 'configured')}Typesense</span>
      <span className="flex items-center gap-1">{dot(s.database === 'tigerdata', true)}{s.database === 'tigerdata' ? 'Tiger Data' : 'Local DB'}</span>
    </div>
  )
}

